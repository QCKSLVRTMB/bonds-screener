def apply_color_filter(res_df, tags_df, selected_colors):
    if not selected_colors:
        return res_df.iloc[0:0], tags_df.iloc[0:0]
    match = pd.Series(False, index=tags_df.index)
    if "green" in selected_colors:
        match = match | (tags_df == "green").any(axis=1)
    if "yellow" in selected_colors:
        match = match | (tags_df == "yellow").any(axis=1)
    if "red" in selected_colors:
        match = match | (tags_df == "red").any(axis=1)
    if "uncolored" in selected_colors:
        match = match | (tags_df == "").all(axis=1)
    return res_df[match], tags_df[match]


