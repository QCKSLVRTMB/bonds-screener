def enrich(df, settlement_date, ndfl, rate_change_pp):
    df = df.copy()

    for src, tgt in [("Дата погашения", "Дней до погашения"),
                     ("Дата оферты", "Дней до оферты")]:
        if src in df.columns:
            df[tgt] = (df[src] - pd.Timestamp(settlement_date)).dt.days

    if "Дата оценки доходности" in df.columns:
        eff = (df["Дата оценки доходности"] - pd.Timestamp(settlement_date)).dt.days
        eff = eff.where(eff >= 0)
        df["Эффективный срок, дней"] = eff
    elif "Дней до погашения" in df.columns:
        df["Эффективный срок, дней"] = df["Дней до погашения"]

    if "Эффективный срок, дней" in df.columns and "Дней до погашения" in df.columns:
        df["Эффективный срок, дней"] = df["Эффективный срок, дней"].fillna(
            df["Дней до погашения"])

    df["Группа надёжности"] = 5
    if "Кредитное качество" in df.columns:
        kq = df["Кредитное качество"]
        if kq.notna().any():
            df.loc[kq >= 9, "Группа надёжности"] = 1
            df.loc[(kq >= 7) & (kq < 9), "Группа надёжности"] = 2
            df.loc[(kq >= 5) & (kq < 7), "Группа надёжности"] = 3
            df.loc[(kq >= 3) & (kq < 5), "Группа надёжности"] = 4
            df.loc[kq < 3, "Группа надёжности"] = 5
        mask_no_kq = kq.isna()
    else:
        mask_no_kq = pd.Series(True, index=df.index)
    if "Уровень листинга" in df.columns:
        level = pd.to_numeric(df["Уровень листинга"], errors="coerce")
        df.loc[mask_no_kq & (level == 1), "Группа надёжности"] = 2
        df.loc[mask_no_kq & (level == 2), "Группа надёжности"] = 3
        df.loc[mask_no_kq & (level == 3), "Группа надёжности"] = 4
    if "Режим торгов" in df.columns:
        df.loc[df["Режим торгов"] == "TQOB", "Группа надёжности"] = 1
    df["Группа надёжности"] = df["Группа надёжности"].astype(int)

    df["YTM, %"] = np.nan
    if "Доходность по последней сделке" in df.columns:
        df["YTM, %"] = df["Доходность по последней сделке"]
    if "Доходность по средневзвешенной цене" in df.columns:
        df["YTM, %"] = df["YTM, %"].fillna(df["Доходность по средневзвешенной цене"])
    df["Чистый YTM, %"] = df["YTM, %"] * (1 - ndfl / 100)

    if "Купон" in df.columns and "Период купона, дней" in df.columns:
        periods_per_year = 365.0 / df["Период купона, дней"].replace(0, np.nan)
        df["Годовой купон"] = df["Купон"] * periods_per_year

    price_col = None
    for c in ("Цена последней сделки, %", "Средневзвешенная цена, % к номиналу"):
        if c in df.columns:
            price_col = c; break

    if price_col and "Ставка купона, %" in df.columns:
        df["Текущая доходность, %"] = np.where(
            df[price_col] > 0, df["Ставка купона, %"] / df[price_col] * 100, np.nan)

    if "Дюрация, дней" in df.columns:
        df["Дюрация, лет"] = df["Дюрация, дней"] / 365
    if "Доходность к оферте" in df.columns:
        df["YTC, %"] = df["Доходность к оферте"]
    if "Доходность к кол-опциону по срвзв." in df.columns:
        df["YTC call, %"] = df["Доходность к кол-опциону по срвзв."]

    if price_col and "Номинал" in df.columns and "НКД" in df.columns:
        df["Грязная цена"] = df[price_col] / 100.0 * df["Номинал"] + df["НКД"]
        if "Размер лота" in df.columns:
            df["Сумма покупки лота"] = df["Грязная цена"] * df["Размер лота"]

    if price_col:
        df["Дисконт к номиналу, %"] = 100.0 - df[price_col]

    # Простая доходность (без реинвестирования, с учётом дисконта)
    if ("Годовой купон" in df.columns and "Грязная цена" in df.columns
            and "Номинал" in df.columns and "Дней до погашения" in df.columns):
        years = df["Дней до погашения"] / 365.0
        years = years.where(years > 0.05)
        df["Простая доходность, %"] = (
            (df["Годовой купон"] + (df["Номинал"] - df["Грязная цена"]) / years)
            / df["Грязная цена"] * 100.0
        )
    else:
        df["Простая доходность, %"] = np.nan

    if (price_col and "Дюрация, лет" in df.columns and "Годовой купон" in df.columns
            and "Номинал" in df.columns and "НКД" in df.columns):
        delta_y = rate_change_pp / 100.0
        convexity = df["Дюрация, лет"] ** 2
        price_change_pct = (-df["Дюрация, лет"] * delta_y
                            + 0.5 * convexity * delta_y ** 2) * 100.0
        df["Прогнозная цена, %"] = df[price_col] * (1 + price_change_pct / 100.0)
        future_dirty = df["Прогнозная цена, %"] / 100.0 * df["Номинал"] + df["НКД"]
        df["Потенциальная доходность, %"] = (
            (future_dirty - df["Грязная цена"] + df["Годовой купон"])
            / df["Грязная цена"] * 100.0
        )

        if "Тип купона" in df.columns:
            floater = df["Тип купона"].astype(str).str.lower().str.contains(
                "плавающ|перемен|формул", na=False)
            df.loc[floater, "Прогнозная цена, %"] = np.nan
            df.loc[floater, "Потенциальная доходность, %"] = np.nan

    def _market_risk(row):
        d = row.get("Дюрация, лет")
        if pd.isna(d):
            return np.nan
        cur = str(row.get("Валюта номинала", "")).upper()
        delta = 2.0 if cur in RUB_CURRENCIES else 1.0
        return -d * delta

    df["Рыночный риск, %"] = df.apply(_market_risk, axis=1)

    def _liquidity(row):
        k = row.get("Коэф. ликвидности")
        n = row.get("Количество сделок")
        if pd.notna(k) and pd.notna(n):
            return (k / 100 * 0.6) + (min(n, 100) / 100 * 0.4)
        if pd.notna(k):
            return k / 100
        if pd.notna(n):
            return min(n, 100) / 100
        return np.nan

    df["Ликвидность (комбинир.)"] = df.apply(_liquidity, axis=1)

    def _nearest_event(row):
        dates = []
        if pd.notna(row.get("Дата оферты")):
            dates.append(("Оферта", row["Дата оферты"]))
        if pd.notna(row.get("Дата погашения")):
            dates.append(("Погашение", row["Дата погашения"]))
        if not dates:
            return pd.Series({"Ближайшая дата, лет": np.nan, "Событие": ""})
        event, dt = min(dates, key=lambda x: x[1])
        years = (dt - pd.Timestamp(settlement_date)).days / 365.0
        return pd.Series({"Ближайшая дата, лет": years, "Событие": event})

    if "Дата оферты" in df.columns or "Дата погашения" in df.columns:
        nearest = df.apply(_nearest_event, axis=1)
        df["Ближайшая дата, лет"] = nearest["Ближайшая дата, лет"]
        df["Событие"] = nearest["Событие"]

    def _bond_type(row):
        labels = []
        cp = str(row.get("Тип купона", "")).lower()
        if any(x in cp for x in ("плавающ", "перемен", "формул")):
            labels.append("Флоатер")
        elif "фикс" in cp:
            labels.append("Фикс")
        fv = str(row.get("Тип номинала", "")).lower()
        if "амортиз" in fv:
            labels.append("Амортизируемая")
        if "индекс" in fv:
            labels.append("Индексируемая")
        if pd.isna(row.get("Дата погашения")):
            labels.append("Вечная")
        if str(row.get("Субординированная", "")).lower() in ("да", "yes"):
            labels.append("Суборд")
        return " · ".join(labels) if labels else "—"

    df["Тип бумаги"] = df.apply(_bond_type, axis=1)

    return df


