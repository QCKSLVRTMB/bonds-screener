def _file_hash(b):
    return hashlib.md5(b).hexdigest()


def init_dohod_session():
    if "dohod_bytes" not in st.session_state:
        st.session_state["dohod_bytes"] = None
        st.session_state["dohod_hash"] = None


def save_dohod_to_session(data):
    st.session_state["dohod_bytes"] = data
    st.session_state["dohod_hash"] = _file_hash(data)


def get_dohod_from_session():
    return st.session_state.get("dohod_bytes")


def clear_dohod_session():
    st.session_state["dohod_bytes"] = None
    st.session_state["dohod_hash"] = None


