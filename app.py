def _fmt_cell(val, base_col):
    if pd.isna(val):
        return ""
    if base_col in DATE_COLS:
        try:
            return pd.Timestamp(val).strftime("%d.%m.%Y")
        except Exception:
            return _html.escape(str(val))
    if base_col in INT_COLS:
        try:
            return f"{int(val):d}"
        except Exception:
            return _html.escape(str(val))
    if isinstance(val, (int, float, np.integer, np.floating)):
        return f"{val:.2f}"
    return _html.escape(str(val))


