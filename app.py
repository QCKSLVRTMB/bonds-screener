@st.cache_data(ttl=600, show_spinner=False)
def _load_securities_cached():
    frames, seen = [], set()
    stop_reason = None
    for page_idx in range(MAX_PAGES):
        page, err = fetch_securities_page(page_idx * PAGE_SIZE, PAGE_SIZE)
        if err:
            stop_reason = f"ошибка: {err}"; break
        if page.empty:
            stop_reason = "пустая страница"; break
        if {"SECID", "BOARDID"}.issubset(page.columns):
            keys = set(zip(page["SECID"], page["BOARDID"]))
            if page_idx > 0 and not (keys - seen):
                stop_reason = "ISS повторяет строки"; break
            seen |= keys
        frames.append(page)
        if len(page) < PAGE_SIZE:
            stop_reason = "последняя страница"; break
    else:
        stop_reason = f"лимит {MAX_PAGES} страниц"
    if not frames:
        return pd.DataFrame(), stop_reason
    df = pd.concat(frames, ignore_index=True)
    if {"SECID", "BOARDID"}.issubset(df.columns):
        df = df.drop_duplicates(subset=["SECID", "BOARDID"])
    return df, stop_reason


