CACHE_DIR = Path.home() / ".moex_bond_screener"
try:
    CACHE_DIR.mkdir(exist_ok=True)
except Exception:
    CACHE_DIR = Path(".")

DOHOD_FILE = CACHE_DIR / "dohod_latest.xlsx"
DOHOD_META = CACHE_DIR / "dohod_meta.json"


def _file_hash(b):
    return hashlib.md5(b).hexdigest()


def save_dohod_bytes(data, source="upload"):
    try:
        DOHOD_FILE.write_bytes(data)
        DOHOD_META.write_text(json.dumps({
            "saved_at": datetime.now().isoformat(),
            "source": source, "size_bytes": len(data),
            "hash": _file_hash(data),
        }, ensure_ascii=False))
    except Exception:
        pass


def load_cached_dohod_bytes():
    if DOHOD_FILE.exists():
        try:
            return DOHOD_FILE.read_bytes()
        except Exception:
            return None
    return None


def get_dohod_cache_age_days():
    if not DOHOD_META.exists():
        return None
    try:
        meta = json.loads(DOHOD_META.read_text())
        saved = datetime.fromisoformat(meta["saved_at"])
        return (datetime.now() - saved).days
    except Exception:
        return None


def clear_dohod_cache():
    for p in (DOHOD_FILE, DOHOD_META):
        try:
            if p.exists():
                p.unlink()
        except Exception:
            pass


