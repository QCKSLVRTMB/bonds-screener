def display_name(col):
    group = COL_GROUP_MAP.get(col, "")
    emoji = GROUP_EMOJI.get(group, "")
    base = f"{col} (X)" if col in EXCEL_COLS else col
    if len(base) > 18:
        for sep in (", ", " "):
            if sep in base:
                parts = base.split(sep)
                mid = len(parts) // 2
                base = sep.join(parts[:mid]) + "\n" + sep.join(parts[mid:])
                break
    return f"{emoji} {base}".strip()


def base_from_display(disp):
    parts = disp.split(" ", 1)
    if parts and parts[0] in GROUP_EMOJI.values():
        base = parts[1] if len(parts) > 1 else ""
    else:
        base = disp
    base = base.replace("\n", " ")
    if base.endswith(" (X)"):
        base = base[:-4]
    return base.strip()


